#!/usr/bin/env python3
"""Export Citrinet's window and sparse mel bank from the pinned 2000 h checkpoint into citrinet_constants.h.

  export_citrinet_constants.py --checkpoint <citrinet384-2000h-best directory> [--check]

The FFT tables (bit reversal, twiddles) are the 512-point ones in quartznet_constants.h: the same n_fft.
"""
import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import torch

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
ENGINE = next(p for p in (ROOT / 'firmware/components/hw1_stt/stt', ROOT / 'components/hardwareone/stt') if p.is_dir())
WEIGHTS_SHA = '9475b593b04efae004a62b7b8c4ed88e52a514ba6f5c49e0fd49c4d1630c798b'
CONFIG_SHA = '358adaae742c3d4dbb1cd86cd2465d1dbca8d8d7f432e83cad0e3de9b6508b4c'
MELS, WINDOW = 80, 400


def digest(data): return hashlib.sha256(data).hexdigest()


def load_state(directory):
    for name, wanted in [('model_weights.ckpt', WEIGHTS_SHA), ('model_config.yaml', CONFIG_SHA)]:
        if digest((directory / name).read_bytes()) != wanted:
            raise ValueError('Pinned Citrinet checkpoint mismatch: ' + name)
    return torch.load(directory / 'model_weights.ckpt', weights_only=True, map_location='cpu')


def generate(state):
    window = state['preprocessor.featurizer.window'].numpy()
    mel = state['preprocessor.featurizer.fb'].numpy().reshape(MELS, 257)
    assert window.shape == (WINDOW,) and window.dtype == mel.dtype == np.float32
    assert np.isfinite(window).all() and np.isfinite(mel).all() and (mel >= 0).all()
    starts, counts, offsets, weights = [], [], [0], []
    for row in mel:
        bins = np.flatnonzero(row)
        assert len(bins) and np.array_equal(bins, np.arange(bins[0], bins[-1] + 1)), 'mel filter is not contiguous'
        starts.append(int(bins[0])); counts.append(len(bins)); weights.extend(row[bins])
        offsets.append(len(weights))

    def array(name, values, kind='float'):
        def value(x): return float(x).hex() + 'f' if kind == 'float' else str(x)
        lines = [', '.join(value(x) for x in values[i:i + 8]) for i in range(0, len(values), 8)]
        return f'inline constexpr {kind} {name}[{len(values)}] = {{\n    ' + ',\n    '.join(lines) + '\n};\n'
    text = ('// Generated by tools/stt_p4/frontend/export_citrinet_constants.py from the pinned Citrinet-384 2000 h\n'
            '// checkpoint (citrinet384-2000h-best). Checkpoint weights: ' + WEIGHTS_SHA + '\n'
            '#pragma once\n#include <cstdint>\nnamespace hw1::stt::citrinet::constants {\n')
    text += array('window', window)
    for name, values in [('mel_start', starts), ('mel_count', counts), ('mel_offset', offsets)]:
        text += array(name, values, 'uint16_t')
    text += array('mel_weight', weights)
    text += '}  // namespace hw1::stt::citrinet::constants\n'
    return text, {'window_sha256_f32le': digest(window.astype('<f4').tobytes()),
                  'mel_sha256_f32le': digest(mel.astype('<f4').tobytes()), 'mel_nonzero': len(weights),
                  'mels': MELS, 'window_samples': WINDOW}


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--checkpoint', type=Path, required=True)
    parser.add_argument('--check', action='store_true', help='fail if the committed files differ')
    args = parser.parse_args()
    content, metadata = generate(load_state(args.checkpoint))
    metadata.update({'schema': 1, 'checkpoint_weights_sha256': WEIGHTS_SHA, 'checkpoint_config_sha256': CONFIG_SHA,
                     'header_sha256': digest(content.encode())})
    outputs = {ENGINE / 'citrinet_constants.h': content,
               HERE / 'citrinet-constants-manifest.json': json.dumps(metadata, indent=2) + '\n'}
    for path, data in outputs.items():
        if args.check:
            if path.read_text() != data:
                raise ValueError('Generated constants differ: ' + path.name)
        else:
            path.write_text(data)
    print(json.dumps(metadata, indent=2))


if __name__ == '__main__':
    main()
