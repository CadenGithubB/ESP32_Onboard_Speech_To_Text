#!/usr/bin/env python3
"""Generate/check the canonical frontend identity consumed by model packaging."""
import argparse
import hashlib
import json
import math
import re
import sys
from pathlib import Path
HERE=Path(__file__).resolve().parent
PRODUCTION=HERE.parents[2]/'firmware/components/hw1_stt/stt'
# Recognizer log-mel guard (2^-24/64, see quartznet_frontend.h). Checked against the C++ and reference.
LOG_GUARD=2**-30

def guards():
    """The log guard as written in the C++ header and in the Python reference; they must agree."""
    header=re.findall(r'inline constexpr float kLogGuard=0x1p-(\d+)f;',(PRODUCTION/'quartznet_frontend.h').read_text())
    reference=re.findall(r'^LOG_GUARD = 2\*\*-(\d+)$',(HERE/'reference_frontend.py').read_text(),re.M)
    if len(header)!=1 or len(reference)!=1: raise SystemExit('kLogGuard / LOG_GUARD not found exactly once')
    return 2.0**-int(header[0]),2.0**-int(reference[0])

def contract_bytes():
    cpp_guard,python_guard=guards()
    if not cpp_guard==python_guard==LOG_GUARD: raise SystemExit(f'Log guard mismatch: C++ {cpp_guard}, reference {python_guard}, contract {LOG_GUARD}')
    files=['quartznet_frontend.h','quartznet_frontend.cpp','quartznet_constants.h','reference_frontend.py','constants-manifest.json']
    value={
        'schema':1,'name':'hw1-quartznet5x5ls-en-frontend-v2',
        'input':{'sample_rate_hz':16000,'dtype':'int16','channels':1,'minimum_samples':320,'maximum_samples':480000,'scale':32768,'preprocessed':False},
        'dither':{'algorithm':'xorshift32-box-muller-float32','seed':'0x12345678','amplitude':1e-5,'reset':'utterance','uniform':'float32(((uint32 >> 8) + 1) / 16777217.0)'},
        'preemphasis':0.97,
        'stft':{'fft':512,'window':320,'hop':160,'center':True,'padding':'reflect','window_source':'checkpoint'},
        'mel':{'bins':64,'source':'checkpoint','sparse_nonzero':498,'power':2,'log_guard':LOG_GUARD},
        'cmvn':{'scope':'whole valid utterance','accumulator':'float64','variance_correction':1,'mean_cast':'float32','variance_cast_before_sqrt':'float32','std_epsilon':1e-5},
        'output':{'dtype':'float32','layout':'T,64','frames':'ceil(samples/160)','padding':False,'maximum_frames':3000},
        'ctc':{'vocabulary':" abcdefghijklmnopqrstuvwxyz'",'blank':28,'argmax_tie':'first','trim':'leading and trailing spaces','maximum_frames':3000},
        'source_sha256':{name:hashlib.sha256(((PRODUCTION if name.endswith(('.cpp','.h')) else HERE)/name).read_bytes()).hexdigest() for name in files},
    }
    return (json.dumps(value,sort_keys=True,indent=2)+'\n').encode()

# Build-time interlock (stt_frontend_interlock.cpp): the firmware refuses to compile unless the packaged
# stt_model_identity.h pins this contract and quartznet_frontend.h still has the guard written here.
# The generated header is deliberately not one of the hashed sources above.
INTERLOCK='quartznet_frontend_contract.h'

def interlock_header(sha):
    exponent=int(round(-math.log2(LOG_GUARD)))
    assert 2.0**-exponent==LOG_GUARD
    return ('// Generated by tools/stt_p4/frontend/contract.py. Do not hand-edit; rerun contract.py.\n'
            '// The recognizer frontend contract this source tree implements (frontend-contract.json).\n'
            '#pragma once\n#include <cstdint>\nnamespace hw1::stt::frontend_contract {\n'
            f'inline constexpr std::uint8_t kSha[32] = {{{", ".join(f"0x{b:02x}" for b in bytes.fromhex(sha))}}};\n'
            f'inline constexpr float kLogGuard = 0x1p-{exponent}f;\n'
            '} // namespace hw1::stt::frontend_contract\n')

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');parser.add_argument('--identity',action='store_true',help='fail unless stt_model_identity.h pins this contract');args=parser.parse_args()
    path=HERE/'frontend-contract.json';data=contract_bytes()
    sha=hashlib.sha256(data).hexdigest();header=PRODUCTION/INTERLOCK;header_text=interlock_header(sha)
    if args.check:
        if not path.exists() or path.read_bytes()!=data: raise SystemExit('Frontend contract is stale')
        if not header.exists() or header.read_text()!=header_text: raise SystemExit(f'{INTERLOCK} is stale: rerun contract.py')
    else: path.write_bytes(data);header.write_text(header_text)
    # The device compares the model header with kFrontendSha (stt_model_container.h), and the firmware build
    # refuses a kFrontendSha other than this contract (stt_frontend_interlock.cpp). Report it here too.
    identity=re.findall(r'kFrontendSha\[32\]\s*=\s*\{([^}]*)\}',(PRODUCTION/'stt_model_identity.h').read_text())
    pinned=''.join(f'{int(x,16):02x}' for x in identity[0].split(',')) if identity else None
    if pinned!=sha:
        message=f'stt_model_identity.h kFrontendSha {pinned} != contract {sha}: install the matching package identity header (the firmware build refuses this mismatch, stt_frontend_interlock.cpp)'
        if args.identity: raise SystemExit(message)
        print('WARNING '+message,file=sys.stderr)
    print(sha)
if __name__=='__main__':main()
